#!/usr/bin/env bun
/**
 * Generate `packages/cli/src/manifest.gen.ts` from the static UI build.
 *
 * The manifest is one `import ... with { type: "file" }` per file in
 * `packages/web/build` plus the pathname → asset map `netlab serve` resolves.
 * `bun build --compile` follows those imports and packs the UI into the binary,
 * so the shipped `netlab` serves the UI with no installation and no build
 * directory next to it.
 *
 * The output is generated and git-ignored; `scripts/verify-binary.sh` and the
 * `compile` script run it before every build. Without it `netlab serve` falls
 * back to reading `packages/web/build` from disk.
 *
 * Usage: bun packages/cli/scripts/gen-manifest.ts
 * Exit codes: 0 when the manifest is written · 1 when the UI build is missing.
 */

import { readdir, stat, writeFile } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";

const CLI_DIR = resolve(import.meta.dir, "..");
const REPO_DIR = resolve(CLI_DIR, "..", "..");
const BUILD_DIR = join(REPO_DIR, "packages", "web", "build");
const OUT_FILE = join(CLI_DIR, "src", "manifest.gen.ts");

/** Every regular file under `dir`, relative to it, sorted for stable output. */
async function walk(dir: string, prefix = ""): Promise<Array<string>> {
  const entries = await readdir(join(dir, prefix), { withFileTypes: true });
  const files: Array<string> = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const name = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) {
      files.push(...(await walk(dir, name)));
    } else if (entry.isFile()) {
      files.push(name);
    }
  }
  return files;
}

/** Import specifier for a build file, relative to the manifest. */
function specifierFor(name: string): string {
  const path = relative(join(CLI_DIR, "src"), join(BUILD_DIR, name))
    .split(sep)
    .join("/");
  return path.startsWith(".") ? path : `./${path}`;
}

async function main(): Promise<number> {
  const shell = join(BUILD_DIR, "index.html");
  const shellInfo = await stat(shell).catch(() => undefined);
  if (shellInfo === undefined || !shellInfo.isFile()) {
    process.stderr.write(
      `no UI build to embed: ${shell} is missing\n` +
        '  build the UI first with "bun run --filter @netlab/web build"\n',
    );
    return 1;
  }
  const files = await walk(BUILD_DIR);
  const imports: Array<string> = [];
  const entries: Array<string> = [];
  files.forEach((name, index) => {
    imports.push(
      `import asset${index} from ${JSON.stringify(specifierFor(name))} with { type: "file" };`,
    );
    entries.push(`  [${JSON.stringify(`/${name}`)}, asset${index}],`);
  });
  const source =
    "// @ts-nocheck\n" +
    "// Generated by packages/cli/scripts/gen-manifest.ts from packages/web/build.\n" +
    "// Do not edit: rerun the generator (or `bun run --cwd packages/cli compile`).\n" +
    `${imports.join("\n")}\n` +
    "\n" +
    "/** Pathname → bundled asset path, consumed by `netlab serve`. */\n" +
    "export const manifestAssets: ReadonlyMap<string, string> = new Map([\n" +
    `${entries.join("\n")}\n` +
    "]);\n";
  await writeFile(OUT_FILE, source, "utf8");
  process.stdout.write(
    `manifest.gen.ts: ${files.length} assets from packages/web/build\n`,
  );
  return 0;
}

process.exit(await main());
